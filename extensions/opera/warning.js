// 🌟 全局初始化
document.addEventListener('DOMContentLoaded', async () => {
    const params = new URLSearchParams(window.location.search);
    const type = params.get('type');

    // 🌟 统一多语言加载引擎
    const langRes = await chrome.storage.local.get('preferred_lang');
    let targetLang = langRes.preferred_lang || (navigator.language || 'en').split('-')[0].toLowerCase();
    if (targetLang === 'zh_CN') targetLang = 'zh';
    let dict = {};
    try {
        const dictRes = await fetch(chrome.runtime.getURL(`popup/locales/${targetLang}.json`));
        if (dictRes.ok) dict = await dictRes.json();
    } catch (e) {
        console.warn('[Warning Page] i18n load failed', e);
    }

    // 全局应用 data-i18n 属性
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) el.textContent = dict[key];
    });

    // 🚀 下载拦截专属逻辑
    if (type === 'download') {
        const reason = params.get('reason');
        const filename = params.get('filename') || 'Unknown File';
        
        if (reason === 'smuggling') {
            const titleEl = document.querySelector('h1');
            if (titleEl) {
                titleEl.textContent = dict['phish_download_smuggling_title'] || '🚨 Malicious Script Blocked';
                titleEl.style.color = '#ef4444';
                titleEl.removeAttribute('data-i18n');
            }
            const descEl = document.querySelector('p');
            if (descEl) {
                const friendlyName = dict['phish_download_smuggling_file'] || 'Obfuscated Local Payload';
                descEl.textContent = (dict['phish_download_smuggling_desc'] || 'DewSecure blocked an inline payload generated by scripts on the page. This is a typical HTML smuggling technique used to bypass network filters.').replaceAll('{filename}', friendlyName);
                descEl.removeAttribute('data-i18n');
            }
            const btnClose = document.getElementById('btn-close');
            if (btnClose) {
                btnClose.textContent = dict['phish_close'] || 'Close this page';
                btnClose.onclick = () => window.close();
            }
            const btnContinue = document.getElementById('btn-continue');
            if (btnContinue) btnContinue.style.display = 'none';
            
            const dangerUrlEl = document.getElementById('danger-url');
            if (dangerUrlEl) {
                dangerUrlEl.textContent = dict['phish_download_smuggling_file'] || 'Obfuscated Local Payload';
                dangerUrlEl.style.color = '#ef4444';
                dangerUrlEl.style.fontWeight = 'bold';
                dangerUrlEl.style.backgroundColor = '#2a1515';
                dangerUrlEl.style.border = '1px solid #ef4444';
            }
            return;
        }

        const titleEl = document.querySelector('h1');
        if (titleEl) {
            titleEl.textContent = dict['phish_download_danger_title'] || '⚠️ High-Risk Download Blocked';
            titleEl.style.color = '#ef4444';
            titleEl.removeAttribute('data-i18n');
        }
        
        const descEl = document.querySelector('p');
        if (descEl) {
            // 🛡️ N-4 修复：改用 textContent，彻底杜绝 XSS 注入
            descEl.style.whiteSpace = 'pre-line';
            const descTemplate = dict['phish_download_danger_desc'] || 'DewSecure blocked the download of {filename}. A double extension (e.g., .pdf.exe) was detected, which is a typical method used by hackers to disguise malware.';
            descEl.textContent = descTemplate.replace('{filename}', filename);
            descEl.removeAttribute('data-i18n');
        }
        
        const dangerUrlEl = document.getElementById('danger-url');
        if (dangerUrlEl) {
            dangerUrlEl.textContent = filename;
            dangerUrlEl.style.color = '#ef4444';
            dangerUrlEl.style.fontWeight = 'bold';
            dangerUrlEl.style.backgroundColor = '#2a1515';
            dangerUrlEl.style.border = '1px solid #ef4444';
        }
        
        const btnContinue = document.getElementById('btn-continue');
        if (btnContinue) {
            btnContinue.textContent = dict['warn_btn_force_download'] || 'I understand the risk, force download';
            btnContinue.removeAttribute('data-i18n');
            btnContinue.onclick = () => {
                const fileUrl = params.get('url');
                if (fileUrl) {
                    btnContinue.disabled = true;
                    btnContinue.textContent = dict['warn_btn_downloading'] || 'Starting download...';
                    
                    chrome.runtime.sendMessage({ type: 'FORCE_DOWNLOAD', url: fileUrl, filename }, () => {
                        setTimeout(() => window.close(), 100);
                    });
                }
            };
        }
        
        const btnClose = document.getElementById('btn-close');
        if (btnClose) {
            btnClose.textContent = dict['phish_close'] || 'Close this page';
            btnClose.removeAttribute('data-i18n');
            btnClose.style.background = '#ef4444';
            btnClose.onclick = () => window.close();
        }
        return;
    }
    
    // 🔒 M-1 修复：杜绝二次 decodeURIComponent 抛错
    const raw = params.get('domain') || params.get('url') || '';
    let targetUrlObj = null;
    let displayDomain = raw;

    if (raw === '\\0' || raw === '%5C0' || !raw) {
        displayDomain = 'Known Malicious Site';
    } else {
        try { 
            targetUrlObj = new URL(/^https?:\/\//i.test(raw) ? raw : `https://${raw}`); 
            displayDomain = targetUrlObj.hostname;
        } catch (e) {
            displayDomain = raw;
        }
    }
    console.log('🛡️ [Warning] 解析到的真实域名:', displayDomain);

    setTimeout(() => {
        const dangerUrlEl = document.getElementById('danger-url');
        if (dangerUrlEl) {
            dangerUrlEl.textContent = displayDomain;
            dangerUrlEl.removeAttribute('data-i18n');
        }

        document.querySelectorAll('div, span, p, h1, h2').forEach(el => {
            const txt = el.textContent.trim();
            if (txt === 'Unknown URL' || txt === 'Unknown Malicious Site' || txt === 'Loading...') {
                el.textContent = displayDomain;
                el.removeAttribute('data-i18n');
            }
        });
    }, 100);

    const btnClose = document.getElementById('btn-close');
    const btnContinue = document.getElementById('btn-continue');

    if (btnClose) {
        btnClose.onclick = () => {
            chrome.tabs.getCurrent(tab => {
                if (tab) chrome.tabs.remove(tab.id);
                else window.close();
            });
        };
    }

    if (btnContinue) {
        btnContinue.onclick = () => {
            if (targetUrlObj && displayDomain !== 'Known Malicious Site') {
                if (!/^https?:$/i.test(targetUrlObj.protocol)) {
                    alert('Invalid URL protocol.');
                    return;
                }
                const pureDomain = targetUrlObj.hostname;
                btnContinue.disabled = true;
                btnContinue.textContent = dict['warn_btn_bypassing'] || "Bypassing...";

                chrome.runtime.sendMessage({ type: 'ADD_TEMP_WHITELIST', domain: pureDomain }, (res) => {
                    if (res && res.ok) {
                        setTimeout(() => {
                            window.location.href = targetUrlObj.href;
                        }, 100);
                    } else {
                        alert(dict['warn_alert_bypass_fail'] || "Failed to bypass, please try again!");
                        btnContinue.disabled = false;
                        btnContinue.textContent = dict['phish_continue'] || "I am an expert, ignore risk";
                    }
                });
            } else {
                window.history.back();
            }
        };
    }

    if (type === 'affiliate') {
        document.title = "DewSecure - Affiliate Link Blocked";
        const h1 = document.querySelector('h1');
        if (h1) {
            h1.textContent = dict['warn_title_affiliate'] || "Malicious Promo Link Blocked";
            h1.removeAttribute('data-i18n');
        }
        const p = document.querySelector('p');
        if (p) {
            p.textContent = dict['warn_desc_affiliate'] || "DewSecure blocked this URL because it contains aggressive tracking or affiliate parameters.";
            p.removeAttribute('data-i18n');
        }
    } else if (type === 'intel') {
        document.title = "DewSecure PRO - Threat Blocked";
        const proTip = document.getElementById('pro-tip');
        if (proTip) proTip.style.display = 'none';

        if (btnClose) {
            btnClose.textContent = dict['phish_close'] || "Close this page";
            btnClose.style.background = "#ef4444";
        }
    } else {
        const { dewsecure_user } = await chrome.storage.local.get('dewsecure_user');
        const isPro = dewsecure_user && ['pro', 'trial', 'family', 'premium'].includes(dewsecure_user.tier);
        const proTip = document.getElementById('pro-tip');
        if (isPro && proTip) proTip.style.display = 'none';

        const reasonsParam = params.get('reasons');
        if (reasonsParam) {
            const dangerUrlEl = document.getElementById('danger-url');
            if (dangerUrlEl) {
                const reasonTitle = dict['warn_reasons_title'] || 'Detection Reasons:';
                const reasonLines = decodeURIComponent(reasonsParam).split(', ').map(r => {
                    const parts = r.split(':');
                    const code = parts[0].replace(/[-+]/g, '_');
                    const arg = parts[1] || '';
                    let text = dict['warn_reason_' + code] || r;
                    return '• ' + text.replace('{arg}', arg);
                });

                const reasonBox = document.createElement('div');
                reasonBox.style.cssText = 'margin-top: 10px; margin-bottom: 20px; padding: 12px; background: #2a1515; border: 1px solid #ef4444; border-radius: 8px; color: #fca5a5; font-size: 13px; text-align: left; width: 100%; box-sizing: border-box;';
                const titleStrong = document.createElement('strong');
                titleStrong.textContent = reasonTitle;
                reasonBox.appendChild(titleStrong);
                reasonBox.appendChild(document.createElement('br'));
                reasonLines.forEach(line => {
                    reasonBox.appendChild(document.createTextNode(line));
                    reasonBox.appendChild(document.createElement('br'));
                });
                dangerUrlEl.parentNode.appendChild(reasonBox);
            }
        }
    }
});
